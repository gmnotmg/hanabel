create policy "admins can update product media" on storage.objects for update to authenticated using (bucket_id = 'product-media' and public.is_admin()) with check (bucket_id = 'product-media' and public.is_admin());
create policy "admins can delete product media" on storage.objects for delete to authenticated using (bucket_id = 'product-media' and public.is_admin());
